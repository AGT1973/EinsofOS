    for ascii_val in range(32, 127):
        ch = chr(ascii_val)
        rows = GLYPHS.get(ch, GLYPHS['?'])
        hex_rows = ', '.join(f'0x{b:02X}' for b in rows)
        f.write(f'    {{ {hex_rows} }}, /* [{ascii_val}] \'{ch}\' */\n')
    f.write('};\n\n')
    f.write('static inline const UINT8* get_glyph(CHAR8 c) {\n')
    f.write('    if (c >= 32 && c <= 126) return einsof_font_8x16[c - 32];\n')
    f.write('    return einsof_font_8x16[\'?\' - 32];\n')
    f.write('}\n\n')
