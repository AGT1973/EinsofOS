class EinsofFramebuffer:
    def __init__(self, width: int = 800, height: int = 600):
        self.width = width
        self.height = height
        # Arreglo plano de píxeles ARGB (cada uno 4 bytes)
        self.pixels = [COLOR_BG_DARK] * (width * height)

    def clear(self, color: int = COLOR_BG_DARK):
        self.pixels = [color] * (self.width * self.height)

    def draw_rect(self, x: int, y: int, w: int, h: int, color: int):
        for j in range(y, min(y + h, self.height)):
            row_offset = j * self.width
            for i in range(x, min(x + w, self.width)):
                self.pixels[row_offset + i] = color

    def draw_rect_outline(self, x: int, y: int, w: int, h: int, border_color: int, thickness: int = 2):
        self.draw_rect(x, y, w, thickness, border_color)  # Top
        self.draw_rect(x, y + h - thickness, w, thickness, border_color)  # Bottom
        self.draw_rect(x, y, thickness, h, border_color)  # Left
        self.draw_rect(x + w - thickness, y, thickness, h, border_color)  # Right

    def draw_text(self, text: str, x: int, y: int, color: int = COLOR_TEXT_WHITE, scale: int = 2):
        cursor_x = x
        for char in text.upper():
            glyph = FONT_8X16_MINIMAL.get(char, FONT_8X16_MINIMAL.get('?'))
            if not glyph:
                cursor_x += 8 * scale
                continue

            for row_idx in range(16):
                byte_val = glyph[row_idx]
                py = y + row_idx * scale
                for col_idx in range(8):
                    if (byte_val >> (7 - col_idx)) & 1:
                        px = cursor_x + col_idx * scale
                        for dy in range(scale):
                            for dx in range(scale):
                                if 0 <= px + dx < self.width and 0 <= py + dy < self.height:
                                    self.pixels[(py + dy) * self.width + (px + dx)] = color
            cursor_x += (8 + 1) * scale

    def export_bmp(self, filepath: str):
        """Exporta el Framebuffer crudo directamente a formato BMP 24/32-bit sin librerías externas."""
        row_size = self.width * 3
        padding = (4 - (row_size % 4)) % 4
        image_size = (row_size + padding) * self.height
        file_size = 54 + image_size

        header = bytearray(54)
        # BMP Header
        header[0:2] = b'BM'
        struct.pack_into('<I', header, 2, file_size)
        struct.pack_into('<I', header, 10, 54) # Offset de píxeles
        # DIB Header (BITMAPINFOHEADER)
        struct.pack_into('<I', header, 14, 40)
        struct.pack_into('<i', header, 18, self.width)
        struct.pack_into('<i', header, 22, self.height) # Bottom-up
        struct.pack_into('<H', header, 26, 1) # Planes
        struct.pack_into('<H', header, 28, 24) # 24 bits BGR
        struct.pack_into('<I', header, 34, image_size)

        with open(filepath, 'wb') as f:
            f.write(header)
            pad_bytes = b'\x00' * padding
            for y in range(self.height - 1, -1, -1):
                row = bytearray()
                offset = y * self.width
                for x in range(self.width):
                    argb = self.pixels[offset + x]
                    b = argb & 0xFF
                    g = (argb >> 8) & 0xFF
                    r = (argb >> 16) & 0xFF
                    row.extend((b, g, r))
                row.extend(pad_bytes)
                f.write(row)
        print(f"[+] Framebuffer exportado a BMP nativo: {filepath} ({self.width}x{self.height})")
