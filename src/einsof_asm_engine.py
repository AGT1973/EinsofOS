#!/usr/bin/env python3
"""
einsof_asm_engine.py — Compilador / Emisor de Assembler Puro para EinsofOS
Arquitectura: Einsof <-> Assembler (Cero C, Cero Libc, Cero Vtables)
Genera codigo x86_64 AVX2 nativo estructurado sobre la Arena de memoria R15.
"""

import os
import sys
import subprocess
from typing import List, Dict, Any

class EinsofAsmEmitter:
    def __init__(self, output_asm_path: str):
        self.output_asm_path = output_asm_path
        self.lines: List[str] = []

    def emit_header(self):
        self.lines.extend([
            "; ==============================================================================",
            "; AUTO-GENERATED BY EINSOF ASM EMITTER (ZERO-C / PURE X86_64 AVX2)",
            "; Modelo: FatPtr (16B) + SlabHeader (64B) sobre Registro Base R15",
            "; ==============================================================================",
            "",
            '%include "einsof_types.inc"',
            "",
            "default rel",
            "",
            "section .data",
            "    align 64",
            '    msg_boot:       db "[+] EINSOF PURE ASM RUNTIME (R15 ARENA): ONLINE", 10',
            "    msg_boot_len:   equ $ - msg_boot",
            '    msg_done:       db "[*] COMPUTO TENSORIAL COMPLETADO (EXIT CODE 0)", 10',
            "    msg_done_len:   equ $ - msg_done",
            "",
            "section .bss",
            "    align 64",
            "    arena_base_ptr: resq 1",
            "",
            "section .text",
            "    global _start",
            "",
            "_start:",
            "    ; 1. Escribir banner de arranque",
            "    mov rax, 1",
            "    mov rdi, 1",
            "    lea rsi, [msg_boot]",
            "    mov rdx, msg_boot_len",
            "    syscall",
            "",
            "    ; 2. Inicializar Arena de memoria (64 MB via sys_mmap)",
            "    mov rax, 9",
            "    xor rdi, rdi",
            "    mov rsi, 67108864",
            "    mov rdx, 3",
            "    mov r10, 34",
            "    mov r8, -1",
            "    xor r9, r9",
            "    syscall",
            "    cmp rax, 0",
            "    jl .error_exit",
            "",
            "    ; FIJAR REGISTRO MAESTRO BASE",
            "    mov r15, rax",
            "    mov [arena_base_ptr], r15",
            ""
        ])

    def emit_vector_hadamard(self, offset_a: int, offset_b: int, offset_dest: int, dim_d: int):
        num_ymm = dim_d // 4
        self.lines.extend([
            f"    ; --- Operacion: Multiplicacion Tensorial Hadamard (D={dim_d}) ---",
            f"    lea rsi, [r15 + {offset_a} + 64]  ; Slab A",
            f"    lea rdi, [r15 + {offset_b} + 64]  ; Slab B",
            f"    lea r8,  [r15 + {offset_dest} + 64] ; Destino C",
            f"    mov rcx, {num_ymm}",
            "",
            f".loop_hadamard_{offset_dest}:",
            "    vmovupd ymm1, [rsi]",
            "    vmovupd ymm2, [rdi]",
            "    vmulpd  ymm3, ymm1, ymm2",
            "    vmovupd [r8], ymm3",
            "    add rsi, 32",
            "    add rdi, 32",
            "    add r8, 32",
            "    dec rcx",
            f"    jnz .loop_hadamard_{offset_dest}",
            ""
        ])

    def emit_footer(self):
        self.lines.extend([
            "    ; 3. Escribir mensaje de finalizacion",
            "    mov rax, 1",
            "    mov rdi, 1",
            "    lea rsi, [msg_done]",
            "    mov rdx, msg_done_len",
            "    syscall",
            "",
            "    ; 4. Salir con Exit Code 0",
            "    mov rax, 60",
            "    xor rdi, rdi",
            "    syscall",
            "",
            ".error_exit:",
            "    mov rax, 60",
            "    mov rdi, 1",
            "    syscall"
        ])

    def save(self):
        with open(self.output_asm_path, "w", encoding="utf-8") as f:
            f.write("\n".join(self.lines) + "\n")
        print(f"[+] Archivo Assembler generado: {self.output_asm_path}")

if __name__ == "__main__":
    out_file = os.path.join(os.path.dirname(__file__), "generated_sample.asm")
    emitter = EinsofAsmEmitter(out_file)
    emitter.emit_header()
    emitter.emit_vector_hadamard(offset_a=0, offset_b=16448, offset_dest=32896, dim_d=2048)
    emitter.emit_footer()
    emitter.save()
